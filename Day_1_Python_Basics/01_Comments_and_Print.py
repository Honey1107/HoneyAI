# 01_Comments_and_Print
# This is a Single-Line Comment

"""
This is a Multi-Line Comment.

Comments are ignored by Python.
They are used to explain code,
improve readability,
and help other developers understand the program.
"""

# Example
age = 24      # Store user's age
# Printing Text
print("Hello World")

# Printing Variables
name = "Jaya"
age = 24

print(name)
print(age)

# Printing Multiple Values
print(name, age)

# Printing with Separator
print("Python", "AI", "Engineer", sep=" | ")

# Printing with End
print("Hello", end=" ")
print("World")

# Escape Characters
print("Welcome\nPython")
print("Welcome\tPython")
print("She said \"Hello\"")

