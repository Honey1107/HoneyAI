# 03_Data_Types
name = "Jaya"                  # str
age = 24                       # int
height = 5.9                   # float
is_engineer = True             # bool
skills = ["Python", "AI"]      # list
location = ("Ahmedabad", "India")  # tuple
technologies = {"Python", "FastAPI"}  # set
student = {
    "name": "Jaya",
    "age": 24
}                              # dictionary

print(type(name))
print(type(age))
print(type(height))
print(type(is_engineer))
print(type(skills))
print(type(location))
print(type(technologies))
print(type(student))
