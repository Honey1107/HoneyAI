# 04_Operators
a = 20
b = 6

# Arithmetic
print(a + b)
print(a - b)
print(a * b)
print(a / b)
print(a // b)
print(a % b)
print(a ** b)

# Comparison
print(a > b)
print(a < b)
print(a == b)
print(a != b)

# Logical
print(a > 10 and b < 10)
print(a < 10 or b < 10)
print(not (a == b))

# Assignment
x = 5
x += 2
x -= 1
x *= 3
print(x)

